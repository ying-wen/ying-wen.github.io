/** Exact deterministic Dyna fixture; schedules are teaching choices, not performance runs. */
export const gamma = 0.9;
export const actions = Object.freeze({S:['go','exit'],A:['cross'],G:[],B:[],D:[]});
export const key=(s,a)=>`${s}:${a}`;
export const oldHistory=Object.freeze([
 {s:'S',a:'go',reward:0,next:'A',done:false},
 {s:'A',a:'cross',reward:1,next:'G',done:true},
 {s:'S',a:'exit',reward:0.6,next:'B',done:true},
]);
export const changeHistory=Object.freeze([
 {...oldHistory[0]}, {s:'A',a:'cross',reward:0,next:'D',done:true},
]);
export const zeroQ=()=>Object.fromEntries(Object.entries(actions).flatMap(([s,aa])=>aa.map(a=>[key(s,a),0])));
export function target(q,row,g=gamma){
 if(!(row.next in actions)||typeof row.done!=='boolean')throw new Error('Invalid outcome');
 if(!row.done&&!actions[row.next].length)throw new Error('Terminal outcome must be marked done');
 return row.reward+(row.done?0:g*Math.max(...actions[row.next].map(a=>q[key(row.next,a)])));
}
export function backup(q,row,alpha=1,g=gamma){
 if(!actions[row.s]?.includes(row.a))throw new Error('Invalid state-action pair');
 const k=key(row.s,row.a),before=q[k],y=target(q,row,g);
 q[k]+=alpha*(y-before);return {pair:k,before,target:y,after:q[k]};
}
export function learner(q=zeroQ()){
 return {q:{...q},model:{},pred:Object.fromEntries(Object.keys(actions).map(s=>[s,[]])),
  counts:{environmentSteps:0,resets:0,directBackups:0,modelWrites:0,modelCalls:0,planningBackups:0,priorityReads:0,queuePops:0},log:[]};
}
export function writeModel(l,row){
 const k=key(row.s,row.a),prev=l.model[k];
 if(prev)l.pred[prev.next]=l.pred[prev.next].filter(p=>p!==k);
 l.model[k]={...row};l.pred[row.next].push(k);l.pred[row.next].sort();l.counts.modelWrites++;
}
export function modelRead(l,pair,purpose){
 const row=l.model[pair];if(!row)throw new Error(`Unobserved pair ${pair}`);
 l.counts.modelCalls++;if(purpose==='priority')l.counts.priorityReads++;
 return row;
}
export function planningBackup(l,pair,alpha=1,g=gamma){
 const event=backup(l.q,modelRead(l,pair,'backup'),alpha,g);
 l.counts.planningBackups++;l.log.push({kind:'planning',...event});return event;
}
export function observe(l,row,{direct=true}={}){
 l.counts.environmentSteps++;
 let event=null;if(direct){event=backup(l.q,row);l.counts.directBackups++;}
 writeModel(l,row);l.log.push({kind:'real',row:{...row},direct:event});return event;
}
export function warmup(){
 const l=learner();observe(l,oldHistory[0]);observe(l,oldHistory[1]);
 planningBackup(l,'S:go');l.counts.resets++;observe(l,oldHistory[2]);return l;
}
export const choice=q=>q['S:go']>q['S:exit']?'go':'exit'; // ties choose exit
export function queueInsert(queue,pair,priority,theta=1e-12){
 if(priority>theta)queue[pair]=Math.max(queue[pair]??0,priority);
}
export function enqueuePredecessors(l,state,queue){
 for(const pair of l.pred[state]){
  const row=modelRead(l,pair,'priority');queueInsert(queue,pair,Math.abs(target(l.q,row)-l.q[pair]));
 }
}
export function popBackup(l,queue){
 const entries=Object.entries(queue).sort((a,b)=>b[1]-a[1]||a[0].localeCompare(b[0]));
 if(!entries.length)return null;
 const [pair,storedPriority]=entries[0];delete queue[pair];l.counts.queuePops++;
 // Recompute using the current model/Q. Every read is charged even for a stale entry.
 const row=modelRead(l,pair,'backup'),residual=Math.abs(target(l.q,row)-l.q[pair]);
 if(residual<=1e-12){l.log.push({kind:'stale-pop',pair,storedPriority,residual});return {pair,skipped:true};}
 const event=backup(l.q,row);l.counts.planningBackups++;
 l.log.push({kind:'queue-backup',storedPriority,residual,...event});
 enqueuePredecessors(l,row.s,queue);return {pair,skipped:false};
}
export function changedLearner(){
 const l=warmup();l.counts.resets++;observe(l,changeHistory[0]);observe(l,changeHistory[1]);return l;
}
function deltaCounts(l,base){return Object.fromEntries(Object.keys(base).map(k=>[k,l.counts[k]-base[k]]));}
function continueInWorld(l){
 l.counts.resets++;const a=choice(l.q),rows=a==='exit'?[oldHistory[2]]:changeHistory;
 // Actual transitions generated by the changed environment, followed by direct/model learning.
 let rewardReturn=0;rows.forEach((row,i)=>{rewardReturn+=gamma**i*row.reward;observe(l,row);});
 return {firstAction:a,route:a==='exit'?['S','B']:['S','A','D'],rewards:rows.map(r=>r.reward),return:rewardReturn,steps:rows.length};
}
export function walkthroughData(){
 const before=warmup(),base={...before.counts},changed=changedLearner(),qAfterDirect={...changed.q};
 const scenarios={};
 for(const name of ['none','scheduled','hybrid']){
  const l=changedLearner(),queue={},snapshots=[{k:0,q:{...l.q},choice:choice(l.q),modelCalls:0}];
  if(name==='scheduled')for(const pair of ['S:exit','A:cross','S:go']){
   planningBackup(l,pair);snapshots.push({k:snapshots.length,q:{...l.q},choice:choice(l.q),modelCalls:l.counts.modelCalls-changed.counts.modelCalls});
  }
  if(name==='hybrid'){
   enqueuePredecessors(l,'A',queue);const initialQueue={...queue};popBackup(l,queue);
   snapshots.push({k:1,q:{...l.q},choice:choice(l.q),modelCalls:l.counts.modelCalls-changed.counts.modelCalls});
   scenarios.hybridQueue=initialQueue;
  }
  const beforeNext={q:{...l.q},choice:choice(l.q),counts:deltaCounts(l,base),snapshots};
  const nextExperience=continueInWorld(l);
  scenarios[name]={...beforeNext,nextExperience,countsAfterNext:deltaCounts(l,base),finalQ:{...l.q}};
 }
 // Textbook §8.4 variant: model/write + queue; no separate direct backup.
 const ps=warmup();ps.counts.resets++;const queue={};
 for(const row of changeHistory){observe(ps,row,{direct:false});queueInsert(queue,key(row.s,row.a),Math.abs(target(ps.q,row)-ps.q[key(row.s,row.a)]));}
 const queues=[{...queue}],pops=[];
 for(let k=0;k<2&&Object.keys(queue).length;k++){pops.push(popBackup(ps,queue));queues.push({...queue});}
 scenarios.textbookPriority={q:{...ps.q},choice:choice(ps.q),queues,pops,counts:deltaCounts(ps,base)};
 return {evidence:'exact-deterministic-mechanism',sampledRuns:0,gamma,alpha:1,actions,oldHistory,changeHistory,
  oldQ:before.q,afterDirectQ:qAfterDirect,oldModel:before.model,newModel:changed.model,
  oldPredecessors:before.pred,newPredecessors:changed.pred,warmupCounts:base,scenarios,
  stochasticCheck:{outcomes:[{probability:.75,target:1},{probability:.25,target:0}],expectation:.75,variance:.1875},
  protocol:{tieBreak:'exit',warmup:'Three real rows in two episodes; one reset and one modeled S:go backup.',
   changed:'S→A→D: two real steps; reset is an episode operation, never a modeled transition.',
   modelCall:'Every outcome row read, including predecessor priority evaluation; direct observed targets are not model calls.',
   priorityPopBudget:2,
   budget:'Comparisons stop after the same two change-discovery transitions; next episodes have different real lengths.',
   information:'Learner knows state/action labels and receives real rows; changed truth is used only to generate the next actual episode.'}};
}
